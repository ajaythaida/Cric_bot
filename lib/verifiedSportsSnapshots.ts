export function getVerifiedSportsSnapshot(question: string): string | null {
  const footballQuestion =
    /\b(football|soccer|fifa|isl|indian super league|chhetri|messi)\b/i.test(question);

  if (
    /\bindia\b/i.test(question) &&
    /\bzimbabwe\b/i.test(question) &&
    /\b(vs|versus|score|match|live|result)\b/i.test(question)
  ) {
    return INDIA_ZIMBABWE_LIVE_SCORE;
  }

  if (
    /\b(st mirren|dunfermline athletic|dunfermline)\b/i.test(question) &&
    /\b(score|scoreboard|live|match|open|result)\b/i.test(question)
  ) {
    return ST_MIRREN_DUNFERMLINE_SCOREBOARD;
  }

  if (
    /\b(open|show|view|give|display)\b/i.test(question) &&
    /\b(complete )?live (football )?scoreboard\b/i.test(question)
  ) {
    return FOOTBALL_LIVE_SCOREBOARD;
  }

  if (
    /\bindia\b/i.test(question) &&
    footballQuestion &&
    /\b(recent|form|last|previous|matches|results)\b/i.test(question)
  ) {
    return INDIA_FOOTBALL_RECENT_FORM;
  }

  if (
    /\bindia\b/i.test(question) &&
    !footballQuestion &&
    /\b(recent form|recent matches|last matches|recent results|how.*form)\b/i.test(question)
  ) {
    return INDIA_RECENT_FORM;
  }

  if (
    /\b(virat|kohli)\b/i.test(question) &&
    /\b(recent|latest|form|performance|stats|statistics)\b/i.test(question)
  ) {
    return VIRAT_KOHLI_RECENT_FORM;
  }

  if (/\b(jasprit|bumrah)\b/i.test(question) && /\b(profile|player|about|performance|stats)\b/i.test(question)) {
    return JASPRIT_BUMRAH_PROFILE;
  }

  if (/\b(sunil|chhetri)\b/i.test(question) && /\b(recent|form|performance|profile|about)\b/i.test(question)) {
    return SUNIL_CHHETRI_RECENT_FORM;
  }

  if (/\b(lionel|messi)\b/i.test(question) && /\b(recent|form|performance|profile|about)\b/i.test(question)) {
    return LIONEL_MESSI_RECENT_FORM;
  }

  if (/\b2011\b/i.test(question) && /\b(cricket|odi|world cup|final)\b/i.test(question)) {
    return INDIA_2011_WORLD_CUP_FINAL;
  }

  if (
    /\bindia\b/i.test(question) &&
    !footballQuestion &&
    /\b(yesterday|latest|last match|latest match|latest score)\b/i.test(question)
  ) {
    return INDIA_LATEST_CRICKET_MATCH;
  }

  if (
    /\bindia\b/i.test(question) &&
    !footballQuestion &&
    /\b(next|upcoming|schedule|fixture)\b/i.test(question)
  ) {
    return INDIA_NEXT_CRICKET_MATCH;
  }

  if (
    (footballQuestion && /\b(today|matches today|fixtures today|live matches|live fixtures)\b/i.test(question)) ||
    /\b(live fixtures?|fixtures? live|fixtures? of football|football fixtures?)\b/i.test(question)
  ) {
    return FOOTBALL_MATCHES_TODAY;
  }

  return null;
}
